//! Generated tokens, Choose-One option cards, and hand spell cards.

use crate::model::{CardId, Keyword, PlayerAuras, Tribe, Unit};

pub const TOKEN_ABERRANT_TENTACLE: CardId = 901;
pub const TOKEN_BEETLE: CardId = 902;
pub const TOKEN_MICROBOT: CardId = 903;
pub const TOKEN_SKELETON: CardId = 904;
pub const TOKEN_BAT: CardId = 905;
pub const TOKEN_WATER_DROPLET: CardId = 906;
pub const TOKEN_DEMON_FODDER: CardId = 907;
pub const TOKEN_FISHBAIT: CardId = 908;

pub const SPELL_BLOOD_GEM: CardId = 950;
pub const SPELL_TAVERN_COIN: CardId = 951;
pub const SPELL_LOCKBOX: CardId = 952;
pub const SPELL_GEM_DAY: CardId = 953;

// Choose-One sub-option cards (presented via `discover_pending`).
pub const CHOICE_CRATER_GEMS: CardId = 980;
pub const CHOICE_CRATER_GEM_DAY: CardId = 981;
pub const CHOICE_GEM_DAY_ATK: CardId = 982;
pub const CHOICE_GEM_DAY_HP: CardId = 983;
pub const CHOICE_BOTANIST_ATK: CardId = 984;
pub const CHOICE_BOTANIST_HP: CardId = 985;
pub const CHOICE_ALLIANCE_ATK: CardId = 986;
pub const CHOICE_ALLIANCE_HP: CardId = 987;

/// Returns `true` if `card_id` is a Choose-One option card rather than a physical unit/spell.
pub fn is_choice_option(card_id: CardId) -> bool {
    (CHOICE_CRATER_GEMS..=CHOICE_ALLIANCE_HP).contains(&card_id)
}

/// `Aberrant Tentacle` (`0/2` Aberration with Taunt, generated by `Zoatroid` and `Underrot Spawn`).
pub fn make_aberrant_tentacle() -> Unit {
    Unit::new("Aberrant Tentacle", 0, 2)
        .with_card_id(TOKEN_ABERRANT_TENTACLE)
        .with_tavern_tier(1)
        .with_tribe(Tribe::Aberration)
        .with_keyword(Keyword::Taunt)
}

/// `Beetle` (`2/2` Beast, or `4/4` if Golden, plus `beetle_bonus_atk / beetle_bonus_hp`).
pub fn make_beetle(is_golden: bool, auras: &PlayerAuras) -> Unit {
    let base = if is_golden { 4 } else { 2 };
    let atk = base + auras.beetle_bonus_atk;
    let hp = base + auras.beetle_bonus_hp;
    let mut u = Unit::new("Beetle", atk, hp)
        .with_card_id(TOKEN_BEETLE)
        .with_tavern_tier(1)
        .with_tribe(Tribe::Beast)
        .with_golden(is_golden);
    u.base_attack = base;
    u.base_health = base;
    u
}

/// `Microbot` (`1/1` Mech, or `2/2` if Golden, summoned by `Cord Puller`).
pub fn make_microbot(is_golden: bool) -> Unit {
    let s = if is_golden { 2 } else { 1 };
    Unit::new("Microbot", s, s)
        .with_card_id(TOKEN_MICROBOT)
        .with_tavern_tier(1)
        .with_tribe(Tribe::Mech)
        .with_golden(is_golden)
}

/// `Skeleton` (`1/1` Undead, or `2/2` if Golden, summoned by `Harmless Bonehead`).
pub fn make_skeleton(is_golden: bool, auras: &PlayerAuras) -> Unit {
    let base = if is_golden { 2 } else { 1 };
    let atk = base + auras.undead_bonus_attack;
    let mut u = Unit::new("Skeleton", atk, base)
        .with_card_id(TOKEN_SKELETON)
        .with_tavern_tier(1)
        .with_tribe(Tribe::Undead)
        .with_golden(is_golden);
    u.base_attack = base;
    u.base_health = base;
    u.undead_attack_applied = auras.undead_bonus_attack;
    u
}

