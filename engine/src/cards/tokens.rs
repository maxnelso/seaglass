/// `Fishbait` (`0/1` Beast, or `0/2` if Golden, generated in shop by `Lurking Lionfish`).
/// Cannot gain stats; Deathrattle gives killer `+5/+5` (`+10/+10` if Golden).
pub fn make_fishbait(is_golden: bool) -> Unit {
    let hp = if is_golden { 2 } else { 1 };
    let mut u = Unit::new("Fishbait", 0, hp)
        .with_card_id(TOKEN_FISHBAIT)
        .with_tavern_tier(2)
        .with_tribe(Tribe::Beast)
        .with_golden(is_golden);
    u.cant_gain_stats = true;
    u
}

/// `Blood Gem` (`+1/+1` targeted spell card, scaled by `blood_gem_bonus_atk / hp` when cast).
pub fn make_blood_gem() -> Unit {
    let mut gem = Unit::new("Blood Gem", 1, 1).with_card_id(SPELL_BLOOD_GEM);
    gem.is_spell = true;
    gem
}

