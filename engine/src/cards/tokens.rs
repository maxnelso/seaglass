/// Returns `true` if `card_id` is a Choose-One option card rather than a physical unit/spell.
pub fn is_choice_option(card_id: CardId) -> bool {
    (CHOICE_CRATER_GEMS..=CHOICE_TIME_MGMT_LATER).contains(&card_id)
}

/// `Aberrant Tentacle` (`0/2` Aberration with Taunt, generated by `Zoatroid` and `Underrot Spawn`).
pub fn make_aberrant_tentacle() -> Unit {
    Unit::new("Aberrant Tentacle", 0, 2)
        .with_card_id(TOKEN_ABERRANT_TENTACLE)
        .with_tavern_tier(1)
        .with_tribe(Tribe::Aberration)
        .with_keyword(Keyword::Taunt)
}

/// `Beetle` (`2/2` Beast, or `4/4` if Golden, plus `beetle_bonus_atk / beetle_bonus_hp`).
pub fn make_beetle(is_golden: bool, auras: &PlayerAuras) -> Unit {
    let base = if is_golden { 4 } else { 2 };
    let atk = base + auras.beetle_bonus_atk;
    let hp = base + auras.beetle_bonus_hp;
    let mut u = Unit::new("Beetle", atk, hp)
        .with_card_id(TOKEN_BEETLE)
        .with_tavern_tier(1)
        .with_tribe(Tribe::Beast)
        .with_golden(is_golden);
    u.base_attack = base;
    u.base_health = base;
    u
}

