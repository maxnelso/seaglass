/// The trinkets' vocabulary: [`VOCAB_IDS`], then the trinkets of the table not in it, in table
/// order.
pub fn vocabulary() -> Vec<CardId> {
    let mut ids = VOCAB_IDS.to_vec();
    for t in TRINKETS {
        if !ids.contains(&t.id) {
            ids.push(t.id);
        }
    }
    ids
}
