#!/usr/bin/env python3
"""Rebuild the engine's Darkmoon Prize table (`engine/src/darkmoon/table.rs`) from HearthstoneJSON's
`CardDefs.xml`, so it can be refreshed each patch (`engine/docs/darkmoon_prizes.md` §9).

    python3 tools/gen_darkmoon_prizes.py path/to/CardDefs.xml [-o engine/src/darkmoon/table.rs]

The prizes are the cards with `BATTLEGROUNDS_DARKMOON_PRIZE_TURN` (tag 1735), whose value is the
prize's Tier (1-4): the `BGS_Treasures_*` spells and the minion `All-Seeing Elder`. For each one:

- its Tier (tag 1735) and whether it is a minion (`CARDTYPE` 4);
- its text, rendered as for Hero Powers (`tools/gen_heroes.py`), with the numbers of its tags 2
  and 3 (`TAG_SCRIPT_DATA_NUM_1/2`); a number the card has no tag for is left as written.

Only the Python standard library is used. The output is deterministic (prizes sorted by Tier, then
name, then card ID).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_dark_gifts import render  # noqa: E402
from gen_heroes import parse, rust_str  # noqa: E402

TAG_CARDTEXT = "184"
TAG_CARDNAME = "185"
TAG_CARDTYPE = "202"
TAG_PRIZE_TIER = "1735"

CARDTYPE_MINION = "4"
CARDTYPE_SPELL = "5"


def prizes(entities: dict[str, dict]) -> list[dict]:
    out = []
    for cid, e in entities.items():
        t = e["tags"]
        if TAG_PRIZE_TIER not in t:
            continue
        kind = t.get(TAG_CARDTYPE)
        if kind not in (CARDTYPE_MINION, CARDTYPE_SPELL):
            sys.exit(f"{cid}: a prize is a spell or a minion (CARDTYPE {kind})")
        out.append(
            {
                "card_id": cid,
                "dbf": e["dbf"],
                "name": render(t.get(TAG_CARDNAME, cid), {}),
                "tier": int(t[TAG_PRIZE_TIER]),
                "minion": kind == CARDTYPE_MINION,
                "text": render(t.get(TAG_CARDTEXT, ""), t),
            }
        )
    out.sort(key=lambda p: (p["tier"], p["name"].lower(), p["card_id"]))
    return out


def generate(build: str, table: list[dict]) -> str:
    out = [
        "//! The Darkmoon Prizes: GENERATED by `tools/gen_darkmoon_prizes.py` from HearthstoneJSON's",
        f"//! `CardDefs.xml` (build {build}). Do not edit: rerun the generator",
        "//! (`docs/darkmoon_prizes.md` §9).",
        "",
        "use super::PrizeData;",
        "",
        "/// The CardDefs build this table was generated from.",
        f"pub const CARD_DEFS_BUILD: u32 = {build if build.isdigit() else 0};",
        "",
        f"/// The Darkmoon Prizes, sorted by Tier, then name ({len(table)} prizes).",
        "pub static PRIZES: &[PrizeData] = &[",
    ]
    for p in table:
        out += [
            "    PrizeData {",
            f"        id: {p['dbf']},",
            f"        card_id: {rust_str(p['card_id'])},",
            f"        name: {rust_str(p['name'])},",
            f"        tier: {p['tier']},",
            f"        minion: {str(p['minion']).lower()},",
            f"        text: {rust_str(p['text'])},",
            "    },",
        ]
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("card_defs", type=Path)
    ap.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "engine/src/darkmoon/table.rs",
    )
    args = ap.parse_args()
    build, entities = parse(args.card_defs)
    table = prizes(entities)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(build, table))
    print(f"wrote {args.output} ({len(table)} prizes)")


if __name__ == "__main__":
    main()
