#!/usr/bin/env python3
"""Rebuild the engine's Dark Gift table (`engine/src/dark_gifts/table.rs`) from HearthstoneJSON's
`CardDefs.xml`, so it can be refreshed each patch (`engine/docs/dark_gifts.md` §9).

    python3 tools/gen_dark_gifts.py path/to/CardDefs.xml [-o engine/src/dark_gifts/table.rs]

The gifts are the spells with `IS_NIGHTMARE_BONUS` (tag 3567) whose card ID starts with
`BG36_MidGameEffect_000t` (the `...t<N>t` cards are another strength of the gift `...t<N>`). For
each one:

- its first and last game turn (tags 4853 and 4854; no tag 4853: from the first turn, no tag
  4854: no last turn);
- its weight in a draw (tag 4856; 100 without it);
- whether `Tras'tath, Soul Parasite`'s Discover can give it (tag 4874);
- its text, rendered as for Hero Powers (`tools/gen_heroes.py`), a number the card has no tag
  for left as written (`{1}`);
- its enchantments: the cards whose ID is its own followed by `e`, `e2`, ... (`...t9e2`), which
  a Power.log attaches to the minion that has the gift.

Two gifts can share a name (`Battle Scars`: `+2/+2` from turn 4, `+3/+3` from turn 7): the one
with the earlier first turn is `<name> (early)`, the other `<name> (late)` (their display names
and file names, `docs/dark_gifts.md` §9).

Only the Python standard library is used. The output is deterministic (gifts sorted by name, then
first turn, then card ID).
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_heroes import parse, plural, rust_str  # noqa: E402

TAG_SCRIPT_DATA_NUM_1 = "2"
TAG_SCRIPT_DATA_NUM_2 = "3"
TAG_SCRIPT_DATA_NUM_3 = "2889"
TAG_CARDTEXT = "184"
TAG_CARDNAME = "185"
TAG_CARDTYPE = "202"
TAG_NIGHTMARE_BONUS = "3567"
TAG_MIN_TURN = "4853"
TAG_MAX_TURN = "4854"
TAG_WEIGHT = "4856"
TAG_TRASTATH = "4874"

CARDTYPE_SPELL = "5"
CARDTYPE_ENCHANTMENT = "6"
PREFIX = "BG36_MidGameEffect_000t"
DEFAULT_WEIGHT = 100


def render(raw: str, tags: dict[str, str]) -> str:
    """The card text as plain text (`gen_heroes.clean_text`), but a `{i}` whose script data tag
    the card doesn't have is left as written."""
    text = html.unescape(raw)
    keys = (TAG_SCRIPT_DATA_NUM_1, TAG_SCRIPT_DATA_NUM_2, TAG_SCRIPT_DATA_NUM_3)
    for i, key in enumerate(keys):
        if key in tags:
            text = text.replace("{%d}" % i, tags[key])
    text = text.replace("[x]", "")
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"\|4\(([^,]*),\s*([^)]*)\)", lambda m: plural(text[: m.start()], m), text)
    text = text.replace("_", " ")
    return " ".join(text.split())


def gifts(entities: dict[str, dict]) -> list[dict]:
    out = []
    for cid, e in entities.items():
        t = e["tags"]
        if not cid.startswith(PREFIX) or t.get(TAG_CARDTYPE) != CARDTYPE_SPELL:
            continue
        if t.get(TAG_NIGHTMARE_BONUS) != "1":
            continue
        enchantments = sorted(
            other
            for other, o in entities.items()
            if o["tags"].get(TAG_CARDTYPE) == CARDTYPE_ENCHANTMENT
            and re.fullmatch(re.escape(cid) + r"e\d*", other)
        )
        out.append(
            {
                "card_id": cid,
                "dbf": e["dbf"],
                "name": render(t.get(TAG_CARDNAME, cid), {}),
                "min_turn": int(t.get(TAG_MIN_TURN, "0")),
                "max_turn": int(t[TAG_MAX_TURN]) if TAG_MAX_TURN in t else None,
                "weight": int(t.get(TAG_WEIGHT, str(DEFAULT_WEIGHT))),
                "trastath": t.get(TAG_TRASTATH) == "1",
                "text": render(t.get(TAG_CARDTEXT, ""), t),
                "enchantments": enchantments,
            }
        )
    out.sort(key=lambda g: (g["name"].lower(), g["min_turn"], g["card_id"]))
    names = [g["name"] for g in out]
    for g in out:
        shared = [o for o in out if o["name"] == g["name"]]
        if len(shared) > 2:
            sys.exit(f"{g['name']}: more than two gifts share the name")
        g["variant"] = None
        if len(shared) == 2:
            g["variant"] = "Early" if shared[0] is g else "Late"
    assert len(names) == len(out)
    return out


def generate(build: str, table: list[dict]) -> str:
    distinct = len({g["name"] for g in table})
    out = [
        "//! The Dark Gifts: GENERATED by `tools/gen_dark_gifts.py` from HearthstoneJSON's",
        f"//! `CardDefs.xml` (build {build}). Do not edit: rerun the generator",
        "//! (`docs/dark_gifts.md` §9).",
        "",
        "use super::{DarkGiftData, Variant};",
        "",
        "/// The CardDefs build this table was generated from.",
        f"pub const CARD_DEFS_BUILD: u32 = {build if build.isdigit() else 0};",
        "",
        f"/// The Dark Gifts, sorted by name ({len(table)} gifts, {distinct} names).",
        "pub static DARK_GIFTS: &[DarkGiftData] = &[",
    ]
    for g in table:
        max_turn = "None" if g["max_turn"] is None else f"Some({g['max_turn']})"
        variant = "None" if g["variant"] is None else f"Some(Variant::{g['variant']})"
        enchantments = ", ".join(rust_str(x) for x in g["enchantments"])
        line = f"        enchantments: &[{enchantments}],"
        if len(line) > 100 or len(enchantments) > 60:  # as rustfmt writes it (array_width 60)
            items = "".join(f"            {rust_str(x)},\n" for x in g["enchantments"])
            line = f"        enchantments: &[\n{items}        ],"
        out += [
            "    DarkGiftData {",
            f"        id: {g['dbf']},",
            f"        card_id: {rust_str(g['card_id'])},",
            f"        name: {rust_str(g['name'])},",
            f"        variant: {variant},",
            f"        min_turn: {g['min_turn']},",
            f"        max_turn: {max_turn},",
            f"        weight: {g['weight']},",
            f"        trastath: {str(g['trastath']).lower()},",
            f"        text: {rust_str(g['text'])},",
            line,
            "    },",
        ]
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("card_defs", type=Path)
    ap.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "engine/src/dark_gifts/table.rs",
    )
    args = ap.parse_args()
    build, entities = parse(args.card_defs)
    table = gifts(entities)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(build, table))
    print(f"wrote {args.output} ({len(table)} gifts)")


if __name__ == "__main__":
    main()
