//! Generates the card rules-text table (`render::text`) from the card sources' doc comments.
//!
//! Each card file under `engine/src/cards/{minions,spells}/` starts with a doc comment: a title
//! line (`` `Name` (`ID`) — Tier 2 Dragon (`3/4`). ``) and then the card's text, either on the next
//! line or after a blank `//!` line. The first paragraph after the title is the card's text; its
//! Markdown (`**bold**`, `` `code` ``, `*italic*`) is stripped. The card is keyed by its
//! `pub const ID: CardId = N;`.

use std::fs;
use std::path::Path;

fn main() {
    let cards = Path::new(env!("CARGO_MANIFEST_DIR")).join("../engine/src/cards");
    let mut entries: Vec<(u32, String)> = Vec::new();
    for dir in ["minions", "spells"] {
        let dir = cards.join(dir);
        println!("cargo:rerun-if-changed={}", dir.display());
        let Ok(files) = fs::read_dir(&dir) else {
            continue;
        };
        for file in files.flatten() {
            let path = file.path();
            if path.extension().is_none_or(|e| e != "rs") {
                continue;
            }
            let source = fs::read_to_string(&path).unwrap_or_default();
            if let (Some(id), Some(text)) = (card_id(&source), card_text(&source)) {
                entries.push((id, text));
            }
        }
    }
    entries.sort();
    entries.dedup_by_key(|(id, _)| *id);
    let mut out = String::from(
        "/// `(card id, rules text)`, sorted by card id (generated by `tools/build.rs`).\n\
         static CARD_TEXT: &[(u32, &str)] = &[\n",
    );
    for (id, text) in &entries {
        out.push_str(&format!("    ({id}, {text:?}),\n"));
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("card_text.rs");
    fs::write(dest, out).unwrap();
}

/// The `N` of `pub const ID: CardId = N;`.
fn card_id(source: &str) -> Option<u32> {
    source.lines().find_map(|line| {
        line.trim()
            .strip_prefix("pub const ID: CardId = ")?
            .strip_suffix(';')?
            .trim()
            .parse()
            .ok()
    })
}

/// The first paragraph of the module doc after its title line, without Markdown.
fn card_text(source: &str) -> Option<String> {
    let docs: Vec<&str> = source
        .lines()
        .take_while(|l| l.starts_with("//!"))
        .map(|l| l.trim_start_matches("//!").trim())
        .collect();
    let mut lines = docs.iter().skip(1).skip_while(|l| l.is_empty());
    let mut paragraph = Vec::new();
    for line in lines.by_ref() {
        if line.is_empty() {
            break;
        }
        paragraph.push(*line);
    }
    let text = strip_markdown(&paragraph.join(" "));
    (!text.is_empty()).then_some(text)
}

fn strip_markdown(text: &str) -> String {
    text.replace("**", "").replace(['`', '*'], "")
}
